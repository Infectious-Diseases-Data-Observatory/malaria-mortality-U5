#!/usr/bin/env Rscript
# Supplementary table (author request, 18 November 2026, after a co-author's comment that the excluded records could
# not be judged without denominators and a breakdown): the child age-band records left out of the primary analysis
# because a covariate was still missing after the declared substitutions, by survey. One row per survey with its
# country, type and year, the covariate that was unavailable (the first one found missing, as recorded by
# R_cbh/primary/00_prepare.R in complete_case_losses.csv), the records and deaths excluded, and their share of the
# survey's eligible records (100% when the whole survey is left out). The last row gives the totals; the caption gives
# them as shares of all eligible records and deaths (the primary sample plus the excluded records, which is the sample
# of the multiple-imputation sensitivity analysis).
# Outputs (<out>/tables/): excluded_records_by_survey.csv, excluded_records_by_survey.latex.txt (LaTeX source saved as
# text, like the other paper tables; no manuscript file is edited), provenance_excluded_records.csv.
source("R_cbh/load_pipeline.R")
source("R_cbh/primary/settings.R")
suppressPackageStartupMessages(library(data.table))
st <- cbh_primary_settings(Sys.getenv("CBH_PRIMARY_VERSION", "gadm"))
out <- file.path(st$out, "tables"); dir.create(out, recursive = TRUE, showWarnings = FALSE)
paths <- c(losses = file.path(st$out, "complete_case_losses.csv"), selection = file.path(st$out, "study_flow/survey_selection.csv"),
  flow = file.path(st$out, "study_flow/flow_counts.csv"), sample = file.path(st$out, "primary_sample.csv"),
  registry = cbh_config()$registry, mics_registry = "data/derived_mics/survey_registry_mics.csv")
stopifnot(all(file.exists(paths)))
x <- fread(paths[["losses"]])
cbh_unique(as.data.frame(x), "survey", "Complete-case losses")
cols <- c("svkey", "iso3", "year", "SurveyType")
reg <- rbind(as.data.table(cbh_read_csv(paths[["registry"]]))[, ..cols], as.data.table(cbh_read_csv(paths[["mics_registry"]]))[, ..cols])
cbh_unique(as.data.frame(reg), "svkey", "Survey registry")
sel <- fread(paths[["selection"]])[, .(survey, kept = complete_case_rows)]
x <- merge(merge(x, reg, by.x = "survey", by.y = "svkey", all.x = TRUE), sel, by = "survey", all.x = TRUE)
stopifnot(!anyNA(x$year), !anyNA(x$kept), all(x$country == x$iso3), all(x$SurveyType %in% c("DHS", "MIS", "MICS")), all(x$rows == x$records))
# Totals agree with the study flow, and the denominators are the primary sample plus the excluded records.
flow <- fread(paths[["flow"]]); counts <- setNames(flow$count, flow$item); sample <- fread(paths[["sample"]])
stopifnot(sum(x$records) == counts[["missing_covariates"]], sum(x$kept == 0) == counts[["excluded_no_covariate"]],
  sum(x$records[x$kept > 0]) == counts[["included_missing_covariates"]])
eligible <- c(records = sample$records + sum(x$records), deaths = sample$deaths + sum(x$deaths))
covariate <- c(wasting_pct = "Wasting and stunting", facility_delivery_pct = "Place of delivery",
  log_health_expenditure_pc = "Health expenditure", electricity_pct = "Electricity", mean_wealth_quintile = "Household wealth")
stopifnot(all(x$missing %in% names(covariate)))
x[, `:=`(country_name = countrycode::countrycode(country, "iso3c", "country.name"), covariate = covariate[missing],
  share_of_survey = records / (records + kept))]
# Somalia's two 2011 MICS surveys are told apart by their zone.
zone <- c(MC_SOM2011NE = " (Northeast Zone)", MC_SOM2011SL = " (Somaliland)")
x[, survey_label := paste0(SurveyType, " ", year, fcoalesce(unname(zone[survey]), ""))]
setorder(x, country_name, year, survey)
stopifnot(!anyDuplicated(x[, .(country_name, survey_label)]))
cbh_atomic_csv(x[, .(survey, iso3 = country, country = country_name, type = SurveyType, year, survey_label, covariate_unavailable = covariate,
  records_excluded = records, deaths_excluded = deaths, records_kept = kept, share_of_survey_records = round(share_of_survey, 4))],
  file.path(out, "excluded_records_by_survey.csv"))

big <- function(v) format(v, big.mark = ",", trim = TRUE, scientific = FALSE)
p1 <- function(v) formatC(100 * v, format = "f", digits = 1)
# The country is printed on its first row only.
x[, shown := fifelse(duplicated(country_name), "", country_name)]
rows <- x[, sprintf("%s & %s & %s & %s & %s & %s \\\\", shown, survey_label, covariate, big(records), big(deaths),
  formatC(100 * share_of_survey, format = "f", digits = 0))]
tex <- c("% Table source; saved as plain text. No manuscript file is edited.",
  "% Generated by R_cbh/reporting/29_excluded_records_table.R.",
  "\\begin{table}[p]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
  sprintf(paste0("\\caption{Child age-band records excluded from the primary analysis because a covariate was unavailable, by survey. ",
    "In all, %s of %s eligible records (%s\\%%) and %s of %s deaths (%s\\%%) were excluded, from %d surveys in %d countries; ",
    "%d surveys were excluded entirely. The covariate shown is the first found to be missing. ",
    "These records are included in the multiple-imputation sensitivity analysis.}"),
    big(sum(x$records)), big(eligible[["records"]]), p1(sum(x$records) / eligible[["records"]]), big(sum(x$deaths)), big(eligible[["deaths"]]),
    p1(sum(x$deaths) / eligible[["deaths"]]), nrow(x), uniqueN(x$country), sum(x$kept == 0)),
  "\\label{stab:exclusions}",
  "\\begin{tabular}{lllrrr}", "\\toprule",
  "Country & Survey & Covariate unavailable & \\begin{tabular}[b]{@{}c@{}}Records\\\\excluded\\end{tabular} & \\begin{tabular}[b]{@{}c@{}}Deaths\\\\excluded\\end{tabular} & \\begin{tabular}[b]{@{}c@{}}\\% of survey's\\\\records\\end{tabular} \\\\",
  "\\midrule", rows, "\\midrule",
  sprintf("All %d surveys & & & %s & %s & \\\\", nrow(x), big(sum(x$records)), big(sum(x$deaths))),
  "\\bottomrule", "\\end{tabular}", "\\end{table}")
writeLines(tex, file.path(out, "excluded_records_by_survey.latex.txt"))
provenance <- c(unname(paths), "R_cbh/reporting/29_excluded_records_table.R", "R_cbh/primary/settings.R")
cbh_atomic_csv(data.frame(file = provenance, md5 = vapply(provenance, cbh_file_hash, "")), file.path(out, "provenance_excluded_records.csv"))
print(x[, .(surveys = .N, records = sum(records), deaths = sum(deaths)), by = covariate][order(-records)])
message(sprintf("Excluded-records table: %d surveys in %d countries; %s records (%s%% of eligible), %s deaths (%s%%)", nrow(x), uniqueN(x$country),
  big(sum(x$records)), p1(sum(x$records) / eligible[["records"]]), big(sum(x$deaths)), p1(sum(x$deaths) / eligible[["deaths"]])))
